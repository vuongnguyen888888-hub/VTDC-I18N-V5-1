#!/usr/bin/env python3
"""Map old Tailwind palette utility names to Figma VIDC primitives without JSX churn.

When Figma lacks a shade, preserve Tailwind's existing value as a documented
exception, rather than inventing a DS value. Reproducible from source export.
"""
import json
import re
from pathlib import Path
root=Path(__file__).resolve().parent.parent
raw_css=(root/'src/tokens/figma-source.css').read_text()
lookup={n:v for n,v in re.findall(r'(?m)^\s*(--vidc-colors-[a-z0-9-]+):\s*(#[0-9A-Fa-f]{6,8});',raw_css)}
source=root/'src'
family={
  'slate':'gray-light-mode', 'gray':'gray-neutral', 'zinc':'gray-iron', 'neutral':'gray-true',
  'stone':'gray-warm', 'red':'brand', 'blue':'blue', 'sky':'blue-light',
  'green':'success', 'emerald':'green', 'lime':'green-light',
  'yellow':'warning', 'amber':'warning', 'orange':'orange',
  'pink':'pink', 'rose':'rose', 'purple':'purple','violet':'violet',
  'indigo':'indigo','cyan':'cyan','teal':'teal','fuchsia':'fuchsia'
}
lines=['/* AUTOGENERATED: Figma VIDC DS V2 controls Tailwind legacy colors.',
       ' * Old JSX uses bg-slate-*, text-red-* etc. Resolve those existing utilities',
       ' * to canonical Figma colors. Tokens missing from Figma remain original Tailwind.',
       ' * Re-run: python scripts/generate-figma-tailwind-palette.py',
       ' */','@theme inline {']
mapping={};missed={}
for old,figma in family.items():
 for shade in ['25','50','100','200','300','400','500','600','700','800','900','950']:
  token=f'--vidc-colors-{figma}-{shade}'
  if token not in lookup:
   missed[f'{old}-{shade}']='Figma primitive missing; native Tailwind fallback preserved';continue
  key=f'--color-{old}-{shade}'
  lines.append(f'  {key}: var({token});')
  mapping[f'{old}-{shade}']={'figmaToken':token,'figmaValue':lookup[token]}
lines+=['}','']
(out:=root/'src/tokens/vidc-tailwind-figma-palette.css').write_text('\n'.join(lines))
# Show how many legacy classes are actually covered by canonical Figma mappings.
used={}
pat=re.compile(r'\b(?:bg|text|border|ring|from|via|to|fill|stroke|outline|divide|decoration|caret)-(slate|gray|zinc|neutral|stone|red|blue|sky|green|emerald|lime|yellow|amber|orange|pink|rose|purple|violet|indigo|cyan|teal|fuchsia)-(25|50|100|200|300|400|500|600|700|800|900|950)\b')
for file in source.rglob('*.tsx'):
 for m in pat.finditer(file.read_text()):
  k=f'{m[1]}-{m[2]}';used[k]=used.get(k,0)+1
covered=sum(n for k,n in used.items() if k in mapping)
missing={k:n for k,n in used.items() if k not in mapping}
report={'source':'Figma JSON source CSS 2026-11-09','strategy':'alias old Tailwind palette class names to Figma primitive CSS via Tailwind v4 @theme inline',
        'mappingCount':len(mapping),'legacyTailwindPaletteUses':sum(used.values()),'figmaCoveredUses':covered,
        'legacyPreservedDueToMissingFigmaShade':missing,'mapping':mapping}
(root/'docs/DS_V2_TAILWIND_FIGMA_MIGRATION.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
print('Figma palette mapped:',len(mapping),'legacy utility references:',sum(used.values()),'covered:',covered,'retained exceptions:',missing)
